#!/usr/bin/env node
'use strict';

/* Uses the bundled Spine 4.1 web runtime (what the browser renderer runs) to
 * write reference numbers for the native backend's parity tests:
 *   node tools/generate-native-reference.js
 * Output: tests/fixtures/spine41/reference.h */

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const fixtures = path.join(root, 'tests', 'fixtures', 'spine41');
const runtimePath = path.join(root, 'data', 'player', 'runtime', '4.1.20', 'spine-player.min.js');

function loadSpine() {
  const context = {
    console,
    window: {},
    document: { createElement: () => ({ style: {}, getContext: () => null }) },
    navigator: { userAgent: 'node' },
    performance: { now: () => 0 },
    requestAnimationFrame: () => 0
  };
  vm.createContext(context);
  vm.runInContext(fs.readFileSync(runtimePath, 'utf8') + '\n;globalThis.spine = spine;', context);
  return context.spine;
}

function loadSkeleton(spine) {
  const atlas = new spine.TextureAtlas(fs.readFileSync(path.join(fixtures, 'spineboy-pma.atlas'), 'utf8'));
  for (const page of atlas.pages) page.setTexture(new spine.FakeTexture({ width: page.width, height: page.height }));
  const binary = new spine.SkeletonBinary(new spine.AtlasAttachmentLoader(atlas));
  return binary.readSkeletonData(new Uint8Array(fs.readFileSync(path.join(fixtures, 'spineboy-pro.skel'))));
}

/* Same steps as SpinePlayer.calculateAnimationViewport (padding is added later). */
function animationBounds(spine, data, name) {
  const skeleton = new spine.Skeleton(data);
  const animation = data.findAnimation(name);
  skeleton.setToSetupPose();
  const steps = 100;
  const stepTime = animation.duration ? animation.duration / steps : 0;
  let time = 0;
  let minX = 100000000, maxX = -100000000, minY = 100000000, maxY = -100000000;
  const offset = new spine.Vector2();
  const size = new spine.Vector2();
  for (let i = 0; i < steps; i++, time += stepTime) {
    animation.apply(skeleton, time, time, false, [], 1, spine.MixBlend.setup, spine.MixDirection.mixIn);
    skeleton.updateWorldTransform();
    skeleton.getBounds(offset, size);
    if (!isNaN(offset.x) && !isNaN(offset.y) && !isNaN(size.x) && !isNaN(size.y)) {
      minX = Math.min(offset.x, minX);
      maxX = Math.max(offset.x + size.x, maxX);
      minY = Math.min(offset.y, minY);
      maxY = Math.max(offset.y + size.y, maxY);
    }
  }
  return [minX, minY, maxX - minX, maxY - minY];
}

/* World vertices in draw order, as the skeleton renderer emits them (no clipping in Spineboy). */
function walkVertices(spine, data) {
  const skeleton = new spine.Skeleton(data);
  const state = new spine.AnimationState(new spine.AnimationStateData(data));
  skeleton.setToSetupPose();
  skeleton.updateWorldTransform();
  state.setAnimation(0, 'walk', true);
  state.update(0.25);
  state.apply(skeleton);
  skeleton.updateWorldTransform();

  const out = [];
  const blocks = [];
  for (const slot of skeleton.drawOrder) {
    const attachment = slot.getAttachment();
    if (!attachment || !slot.bone.active) continue;
    const alpha = skeleton.color.a * slot.color.a * attachment.color.a;
    if (slot.color.a === 0 || attachment.color.a === 0 || alpha === 0) continue;
    let vertices = null;
    if (attachment instanceof spine.RegionAttachment) {
      vertices = new Array(8);
      attachment.computeWorldVertices(slot, vertices, 0, 2);
    } else if (attachment instanceof spine.MeshAttachment) {
      vertices = new Array(attachment.worldVerticesLength);
      attachment.computeWorldVertices(slot, 0, attachment.worldVerticesLength, vertices, 0, 2);
    } else if (attachment instanceof spine.ClippingAttachment) {
      throw new Error('fixture unexpectedly uses clipping');
    }
    if (vertices) {
      out.push(...vertices);
      blocks.push(vertices.length / 2);
    }
  }
  return { vertices: out, blocks };
}

function floats(values) {
  return values.map(function (value) { return `${value.toFixed(5)}f`; }).join(', ');
}

function main() {
  const spine = loadSpine();
  const data = loadSkeleton(spine);
  const names = data.animations.map(function (animation) { return animation.name; });
  const idle = animationBounds(spine, data, 'idle');
  const walk = animationBounds(spine, data, 'walk');
  const walkDraw = walkVertices(spine, data);
  const vertices = walkDraw.vertices;

  const lines = [
    '/* Generated by tools/generate-native-reference.js from the bundled Spine 4.1.20 web runtime. Do not edit. */',
    '#pragma once',
    '',
    `static const char *const REF_ANIMATION_NAMES[] = {${names.map(function (name) { return JSON.stringify(name); }).join(', ')}};`,
    `#define REF_ANIMATION_COUNT ${names.length}`,
    `static const float REF_BOUNDS_IDLE[4] = {${floats(idle)}};`,
    `static const float REF_BOUNDS_WALK[4] = {${floats(walk)}};`,
    '/* Vertices per attachment, in draw order. Region quads (4) may start at a different corner per runtime. */',
    `#define REF_WALK_BLOCK_COUNT ${walkDraw.blocks.length}`,
    `static const int REF_WALK_BLOCKS[${walkDraw.blocks.length}] = {${walkDraw.blocks.join(', ')}};`,
    `#define REF_WALK_VERTEX_COUNT ${vertices.length / 2}`,
    `static const float REF_WALK_VERTICES[${vertices.length}] = {`
  ];
  for (let i = 0; i < vertices.length; i += 8) lines.push(`\t${floats(vertices.slice(i, i + 8))},`);
  lines.push('};', '');
  fs.writeFileSync(path.join(fixtures, 'reference.h'), lines.join('\n'));
  console.log(`idle bounds ${idle.map((v) => v.toFixed(2)).join(', ')}`);
  console.log(`walk bounds ${walk.map((v) => v.toFixed(2)).join(', ')}`);
  console.log(`${vertices.length / 2} walk vertices, ${names.length} animations`);
}

main();
