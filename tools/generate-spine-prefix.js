#!/usr/bin/env node
'use strict';

/* Writes the forced-include header that renames a vendored spine-c runtime's
 * external symbols. Feed it the symbol table of the *unprefixed* build:
 *
 *   cmake --build build --config RelWithDebInfo --target spine-c-41-raw
 *   dumpbin -symbols build/obs-spine-player/RelWithDebInfo/spine-c-41-raw.lib > sp41.txt
 *   node tools/generate-spine-prefix.js --tool dumpbin --prefix sp41_ \
 *     --version third_party/spine-c-4.1/VERSION --out src/native/spine41-prefix.h sp41.txt
 *
 * Rerun only when the vendored runtime changes. */

const fs = require('node:fs');
const path = require('node:path');
const { parseSymbols, prefixNames } = require('./spine-symbols.js');

function parseArgs(argv) {
  const options = { tool: null, prefix: null, out: null, version: null, machO: false, input: null };
  for (let index = 0; index < argv.length; index++) {
    const arg = argv[index];
    if (arg === '--tool') options.tool = argv[++index];
    else if (arg === '--prefix') options.prefix = argv[++index];
    else if (arg === '--out') options.out = argv[++index];
    else if (arg === '--version') options.version = argv[++index];
    else if (arg === '--macho') options.machO = true;
    else options.input = arg;
  }
  if (!options.tool || !options.prefix || !options.out || !options.input) {
    throw new Error('usage: generate-spine-prefix.js --tool dumpbin|nm --prefix sp41_ --out header.h [--version FILE] [--macho] symbols.txt');
  }
  return options;
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  const parsed = parseSymbols(fs.readFileSync(options.input, 'utf8'), options.tool, { machO: options.machO });
  const names = prefixNames(parsed, options.prefix);
  if (!names.length) throw new Error(`no symbols found in ${options.input}`);

  const guard = path.basename(options.out).toUpperCase().replace(/[^A-Z0-9]/g, '_');
  const commit = options.version ? fs.readFileSync(options.version, 'utf8').trim() : 'unknown';
  const lines = [
    '/* Generated by tools/generate-spine-prefix.js. Do not edit. */',
    `/* Renames the external symbols of the vendored spine-c runtime (commit ${commit}). */`,
    `#ifndef ${guard}`,
    `#define ${guard}`,
    '',
    ...names.map(function (name) { return `#define ${name} ${options.prefix}${name}`; }),
    '',
    '#endif',
    ''
  ];
  fs.writeFileSync(options.out, lines.join('\n'));
  console.log(`wrote ${names.length} renames to ${options.out}`);
}

try {
  main();
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
